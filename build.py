#!/usr/bin/env python3
"""Index markdown notes into viewer/graphdata.js (for the browser) and index.json (for the server).

Usage: python3 build.py [NOTES_DIR]   (defaults to ./notes)
Standard library only.
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
NOTES_DIR = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else os.path.join(ROOT, "notes")
VIEWER_OUT = os.path.join(ROOT, "viewer", "graphdata.js")
INDEX_OUT = os.path.join(ROOT, "index.json")  # full text for the server; never served to the browser
EXCERPT_CHARS = 700
WIKILINK = re.compile(r"\[\[([^\]|#]+)(?:[#|][^\]]*)?\]\]")


def label_from_filename(path):
    name = os.path.splitext(os.path.basename(path))[0]
    return re.sub(r"[-_]+", " ", name).strip()


def clean_excerpt(text):
    text = re.sub(r"^---\n.*?\n---\n", "", text, flags=re.S)        # YAML front matter
    text = re.sub(r"^\s*#\s+[^\n]*\n", "", text, count=1)              # leading H1 (it's the label)
    text = WIKILINK.sub(lambda m: m.group(1), text)                   # [[Link]] -> Link
    text = re.sub(r"^#+\s*", "", text, flags=re.M)                    # heading markers
    text = re.sub(r"[*_`>]", "", text)
    text = re.sub(r"\s+", " ", text).strip()
    if len(text) <= EXCERPT_CHARS:
        return text
    cut = text[:EXCERPT_CHARS]
    return cut[: cut.rfind(" ")] + "…" if " " in cut else cut + "…"


def main():
    if not os.path.isdir(NOTES_DIR):
        sys.exit(f"Notes folder not found: {NOTES_DIR}")

    paths = []
    for dirpath, dirnames, filenames in os.walk(NOTES_DIR):
        dirnames[:] = sorted(d for d in dirnames if not d.startswith("."))
        paths += [os.path.join(dirpath, f) for f in sorted(filenames) if f.lower().endswith(".md")]
    paths.sort(key=lambda p: os.path.relpath(p, NOTES_DIR).lower())

    nodes, docs = [], []
    for i, path in enumerate(paths):
        with open(path, encoding="utf-8", errors="replace") as f:
            text = f.read()
        rel = os.path.relpath(path, NOTES_DIR)
        parent = os.path.dirname(rel)
        group = os.path.basename(parent) if parent else "root"
        label = label_from_filename(path)
        wikis = {w.strip().lower() for w in WIKILINK.findall(text)}
        nodes.append({"id": i, "label": label, "group": group, "path": rel,
                      "excerpt": clean_excerpt(text)})
        docs.append({"id": i, "label": label, "group": group, "path": rel,
                     "text": text, "wikis": wikis, "lower": text.lower()})

    # Links: A mentions B's title (plain text or [[wikilink]]), or A and B share a wikilink target.
    pairs = {}
    title_res = [re.compile(r"(?<![\w])" + re.escape(d["label"].lower()) + r"(?![\w])") for d in docs]
    for a in docs:
        for b in docs:
            if a["id"] == b["id"]:
                continue
            key = (min(a["id"], b["id"]), max(a["id"], b["id"]))
            if b["label"].lower() in a["wikis"] or title_res[b["id"]].search(a["lower"]):
                pairs[key] = pairs.get(key, 0) + 1
            elif a["id"] < b["id"] and (a["wikis"] & b["wikis"]):
                pairs[key] = pairs.get(key, 0) + 0.5
    links = [{"source": s, "target": t, "weight": w} for (s, t), w in sorted(pairs.items())]

    degree = [0] * len(nodes)
    for l in links:
        degree[l["source"]] += 1
        degree[l["target"]] += 1
    for n in nodes:
        n["degree"] = degree[n["id"]]

    assert all(n["id"] == i for i, n in enumerate(nodes)), "node id must equal array index"

    os.makedirs(os.path.dirname(VIEWER_OUT), exist_ok=True)
    with open(VIEWER_OUT, "w", encoding="utf-8") as f:
        f.write("// Generated by build.py — do not edit.\n")
        f.write("const GRAPH = " + json.dumps({"nodes": nodes, "links": links}, ensure_ascii=False) + ";\n")
    with open(INDEX_OUT, "w", encoding="utf-8") as f:
        json.dump([{k: d[k] for k in ("id", "label", "group", "path", "text")} for d in docs],
                  f, ensure_ascii=False)

    groups = sorted({n["group"] for n in nodes})
    print(f"Indexed {len(nodes)} notes, {len(links)} links, {len(groups)} groups: {', '.join(groups)}")
    print(f"Wrote {os.path.relpath(VIEWER_OUT, ROOT)} and {os.path.relpath(INDEX_OUT, ROOT)}")


if __name__ == "__main__":
    main()
